import { toIsoDate } from './financeEngine';
import { FinanceDataset } from './types';

function daysAgoIso(daysAgo: number, ref = new Date()): string {
  const d = new Date(ref.getFullYear(), ref.getMonth(), ref.getDate() - daysAgo);
  return toIsoDate(d);
}

function monthDayIso(monthsAgo: number, day: number, ref = new Date()): string {
  const d = new Date(ref.getFullYear(), ref.getMonth() - monthsAgo, Math.min(day, 28));
  return toIsoDate(d);
}

